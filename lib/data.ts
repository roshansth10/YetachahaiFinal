export interface User {
  id: string
  name: string
  email: string
  password: string
  role: 'customer' | 'admin'
  avatar?: string
  phone?: string
  address?: string | {
    line1: string
    line2?: string
    city: string
    district: string
    province: string
    postalCode: string
  }
  memberSince: string
  booksOrdered: number
  totalSpent: number
  preferredPayment?: 'esewa' | 'khalti' | 'cod'
  createdAt: string
}

export interface Order {
  id: string
  userId: string
  items: { bookId: string; quantity: number; price: number; format?: string }[]
  subtotal: number
  shipping: number
  discount: number
  total: number
  status: 'pending' | 'confirmed' | 'processing' | 'shipped' | 'delivered' | 'cancelled'
  paymentMethod: 'esewa' | 'khalti' | 'cod'
  paymentStatus: 'paid' | 'pending' | 'failed' | 'refunded'
  transactionId?: string
  paymentDate?: string
  shippingAddress: {
    name: string
    phone: string
    line1: string
    line2?: string
    city: string
    district: string
    province: string
    postalCode: string
    notes?: string
  }
  shippingMethod: 'standard' | 'express' | 'sameday'
  createdAt: string
  estimatedDelivery: string
}

export interface Review {
  id: string
  bookId: string
  userId: string
  userName: string
  rating: number
  title: string
  content: string
  createdAt: string
  helpful: number
}

export interface Category {
  id: string
  name: string
  slug: string
  description: string
  icon: string
  bookCount: number
}

export interface BlogPost {
  id: string
  title: string
  slug: string
  excerpt: string
  content: string
  coverImage: string
  author: string
  category: string
  createdAt: string
  readTime: number
}

export interface Coupon {
  id: string
  code: string
  discount: number
  type: 'percentage' | 'fixed'
  minOrder: number
  maxDiscount?: number
  validFrom: string
  validUntil: string
  usageLimit: number
  usedCount: number
  isActive: boolean
}

