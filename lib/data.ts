// Helper functions
export function getBookById(idOrSlug: string): Book | undefined {
  return mockBooks.find(book => book.id === idOrSlug || book.slug === idOrSlug)
}

export function getBookBySlug(slug: string): Book | undefined {
  return mockBooks.find(book => book.slug === slug || book.id === slug)
}

export function getBooksByGenre(genre: string): Book[] {
  const gLower = genre.toLowerCase()
  return mockBooks.filter(book => 
    book.genres.some(g => g.toLowerCase() === gLower) ||
    book.category?.toLowerCase() === gLower
  )
}

export function getBestsellers(): Book[] {
  return mockBooks.filter(book => book.isBestseller)
}

export function getNewArrivals(): Book[] {
  return mockBooks.filter(book => book.isNewArrival)
}

export function getFeaturedBooks(): Book[] {
  return mockBooks.filter(book => book.isFeatured)
}

export function searchBooks(query: string): Book[] {
  const lowerQuery = query.toLowerCase().trim()
  if (!lowerQuery) return mockBooks
  return mockBooks.filter(book => 
    book.title.toLowerCase().includes(lowerQuery) ||
    book.author.toLowerCase().includes(lowerQuery) ||
    book.genres.some(g => g.toLowerCase().includes(lowerQuery)) ||
    book.description.toLowerCase().includes(lowerQuery)
  )
}
